const CAT_ICON = { champions: "star", science: "brain", stories: "heart", tips: "bulb" };

// Ένας σταθερός αριθμός από το slug (FNV-1a), για να μην αλλάζει το γραφικό από build σε build
function seedOf(str) {
  let h = 2166136261;
  for (const ch of str) h = Math.imul(h ^ ch.codePointAt(0), 16777619);
  return h >>> 0;
}

function postArt(post) {
  const s = seedOf(post.slug);
  const icon = ICONS[post.icon] || ICONS[CAT_ICON[post.cat]];
  if (!icon) throw new Error(`Άγνωστο artIcon «${post.icon}» στο ${post.slug}`);
  const angle = (s % 37) - 18; // −18° έως 18°
  const side = (s >> 6) & 1 ? 1 : -1; // οι γραμμές από αριστερά ή από δεξιά
  const cx = 160 + side * (40 + ((s >> 8) % 40));
  const cy = 90 + (((s >> 14) % 50) - 25);
  const lanes = [0, 1, 2, 3]
    .map((i) => {
      const w = 230 + i * 34;
      const h = 110 + i * 34;
      return `<rect x="${cx - w / 2}" y="${cy - h / 2}" width="${w}" height="${h}" rx="${h / 2}"/>`;
    })
    .join("");
  const dx = side > 0 ? 22 : 238; // οι τελίτσες στην αντίθετη γωνία από τις γραμμές
  const dots = [];
  for (let r = 0; r < 4; r++) for (let c = 0; c < 5; c++) dots.push(`<circle cx="${dx + c * 14}" cy="${22 + r * 14}" r="1.6"/>`);
  return (
    `<div class="post-art" data-cat="${post.cat}" aria-hidden="true">` +
    `<svg viewBox="0 0 320 180" preserveAspectRatio="xMidYMid slice" focusable="false">` +
    `<g class="pa-lanes" transform="rotate(${angle} ${cx} ${cy})">${lanes}</g>` +
    `<g class="pa-dots">${dots.join("")}</g>` +
    `<circle class="pa-halo" cx="160" cy="90" r="50"/>` +
    `<svg class="pa-icon" x="124" y="54" width="72" height="72" viewBox="0 0 24 24">${icon}</svg>` +
    `</svg></div>`
  );
}

